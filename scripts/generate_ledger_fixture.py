#!/usr/bin/env python3
"""Generate the Foundation-only app fixture from the reviewed integer-cent data."""
import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'docs/analysis/ledger-data-20261110.json'
TARGET = ROOT / 'ABank/Data/BankingDemoFixture.generated.swift'


def literal(value):
    return json.dumps(value or '', ensure_ascii=False)


def render():
    raw = SOURCE.read_bytes()
    data = json.loads(raw)
    loan = data['loan']
    rows = data['transactions']
    balance = data['account']['opening_balance_cents']
    assert len(rows) == 37
    for row in rows:
        assert type(row['amount_cents']) is int and row['amount_cents'] > 0
        assert row['balance_before_cents'] == balance
        balance += row['amount_cents'] * (1 if row['direction'] == 'income' else -1)
        assert balance == row['balance_after_cents'] and balance >= 0
    assert balance == data['account']['current_balance_cents'] == 826923
    # Internal ordering slots are explicitly synthetic, never displayed as source timestamps.
    ordering = {
        'fixture-2026-08-25-carryover-adjustment': '12:00:00',
        'fixture-2026-09-21-interest': '00:00:00',
        'fixture-2026-10-09-loan-repayment': '00:48:00',
        'fixture-2026-10-10-salary': '16:00:00',
        'fixture-2026-10-10-transfer-to-ou': '16:05:00',
        'fixture-2026-10-10-wechat': '16:10:00',
        'fixture-2026-11-09-loan-repayment': '00:48:00',
    }
    icons = {'salary': 'yensign.circle', 'loan_repay': 'house.fill',
             'transfer_out': 'arrow.up.right', 'transfer_in': 'arrow.down.left',
             'interest_income': 'banknote', 'other_expense': 'creditcard'}
    lines = [
        '// Generated by scripts/generate_ledger_fixture.py. Do not edit by hand.',
        f'// Source SHA-256: {hashlib.sha256(raw).hexdigest()}',
        'import Foundation', '', 'enum BankingDemoFixture {',
        f'    static let version = {literal(data["dataset_id"])}',
        '    static func makeRecord() -> FinanceLedgerRecord {',
        '        let accountID = FinanceLedgerRecord.defaultAccountId',
        '        let transactions: [LedgerTransaction] = [',
    ]
    for row in rows:
        icon = icons.get(row['category_id'], 'message' if row['title'] == '微信支付' else 'creditcard')
        lines += [
            f'            // {row["origin"]}: {row["source_note"]}',
            '            LedgerTransaction(',
            f'                id: {literal(row["id"])}, accountId: accountID, date: {literal(row["date"])}, time: {literal(row["time"])},',
            f'                title: {literal(row["title"])}, direction: .{row["direction"]}, amount: TransferMoney.amount({row["amount_cents"]}), balanceAfter: TransferMoney.amount({row["balance_after_cents"]}),',
            f'                iconKey: {literal(icon)}, categoryId: {literal(row["category_id"])},',
            f'                counterpartyName: {literal(row["counterparty_name"])}, counterpartyAccount: {literal(row["counterparty_account_masked"])},',
            f'                summary: {literal(row["title"])}, postscript: {literal(row["postscript"])}, cardNumber: "6230****8472", transactionType: {literal("贷款还款" if row["category_id"] == "loan_repay" else "转账")},',
            f'                channel: {literal(row["channel"] or "—")}, orderingTime: {literal(ordering[row["id"]]) if not row["time"] else "nil"}',
            '            ),',
        ]
    lines += [
        '        ]',
        '        var loan = LoanContract(',
        '            id: FinanceLedgerRecord.defaultLoanId, name: "个人住房贷款",',
        f'            unpaidPrincipal: TransferMoney.amount({loan["current_outstanding_principal_cents"]}), contractLimit: 0,',
        f'            expiryDate: {literal(loan["maturity_date"])}, monthlyDue: 0, availableLimit: 0, isDetailExpanded: true,',
        '            loanAmount: 0, annualRatePercent: 3.2, pricingMethod: "固定利率",',
        '            maturityDateText: "2037年10月8日",',
        f'            installmentAmount: TransferMoney.amount({loan["monthly_payment_cents"]}), remainingTerms: {loan["remaining_periods"]},',
        f'            nextDueDate: {literal(loan["next_due_date"])}, nextPeriod: 4',
        '        )',
        '        loan.hasOriginalContractDetails = false',
        f'        loan.finalDueDate = {literal(loan["maturity_date"])}',
        '        loan.recordedRepayments = [',
    ]
    for period, row in enumerate(loan['recorded_payment_history'], 1):
        lines.append(f'            RecordedLoanRepayment(period: {period}, date: {literal(row["date"])}, principalInCents: {row["principal_repaid_cents"]}, interestInCents: {row["interest_cents"]}, balanceInCents: {row["closing_principal_cents"]}),')
    lines += [
        '        ]',
        '        var record = FinanceLedgerRecord(',
        '            accounts: [LedgerAccount(id: accountID, tailNumber: "8472", currency: "人民币",',
        f'                balance: TransferMoney.amount({balance}), openingBalance: TransferMoney.amount({data["account"]["opening_balance_cents"]}))],',
        '            transactions: transactions, loanContracts: [loan],',
        '            assetLiabilityAnnouncement: "美好生活，从一点一滴存钱开始~",',
        '            dataTimestamp: "2026-11-10 19:22:30"',
        '        )',
        '        record.demoDataVersion = version',
        '        return record',
        '    }',
        '}', '',
    ]
    return '\n'.join(lines)


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    expected = render()
    if args.check:
        if not TARGET.exists() or TARGET.read_text() != expected:
            raise SystemExit('Fixture differs from reviewed JSON; run scripts/generate_ledger_fixture.py')
        print('Generated fixture matches reviewed JSON')
    else:
        TARGET.write_text(expected)
        print(TARGET.relative_to(ROOT))
